    UNION ALL SELECT 'CON-LUMBER-CORSET', 'LUMBER CORSET'
    UNION ALL SELECT 'CON-KNEE-BRACE', 'KNEE BRACE'
    UNION ALL SELECT 'CON-NECK-COLLAR', 'NECK COLLAR'
    UNION ALL SELECT 'CON-AIR-FRESHNER', 'AIR FRESHNER'
    UNION ALL SELECT 'CON-REFUSE-BAG', 'REFUSE BAG'
    UNION ALL SELECT 'CON-IZAL', 'IZAL'
    UNION ALL SELECT 'CON-CELLOPHANE', 'CELLOPHANE'
