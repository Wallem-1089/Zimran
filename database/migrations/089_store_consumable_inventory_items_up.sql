) seed
INNER JOIN users u
    ON u.id = (
        SELECT u2.id
        FROM users u2
        ORDER BY CASE WHEN u2.username = 'walter' THEN 0 ELSE 1 END, u2.id
        LIMIT 1
    )
WHERE NOT EXISTS (
    SELECT 1
    FROM inventory_items existing
    WHERE existing.item_code = seed.item_code
       OR UPPER(TRIM(existing.item_name)) = seed.item_name
);
