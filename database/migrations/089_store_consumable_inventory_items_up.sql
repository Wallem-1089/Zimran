    item_code,
    item_name,
    category,
    unit,
    description,
    billable_item_id,
    is_active,
    created_by,
    created_at,
    updated_at
)
SELECT seed.item_code,
       seed.item_name,
       'Consumable',
       'Unit',
       'Store consumable inventory item.',
       NULL,
       1,
       u.id,
       NOW(),
       NOW()
FROM (
    SELECT 'CON-CRUTCHES' AS item_code, 'CRUTCHES' AS item_name
    UNION ALL SELECT 'CON-CREPE-BANDAGES', 'CREPE BANDAGES'
    UNION ALL SELECT 'CON-2ML-SYRINGES', '2ML SYRINGES'
