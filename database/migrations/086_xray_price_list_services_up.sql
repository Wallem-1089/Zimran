-- Seed X-Ray price-list services as active billable service items.

INSERT INTO billable_items (
    item_code,
    item_name,
    item_type,
    department_id,
    description,
    unit_price,
    unit,
    is_active,
    created_by
)
SELECT seed.item_code,
       seed.item_name,
       'Service',
       d.id,
       'X-Ray service price list item.',
       seed.unit_price,
       'Study',
       1,
       u.id
FROM (
    SELECT 'XRAY-HAND-APLAT' AS item_code, 'HAND(AP/LAT)' AS item_name, 12000.00 AS unit_price
    UNION ALL SELECT 'XRAY-BOTH-HAND', 'BOTH HAND', 22000.00
    UNION ALL SELECT 'XRAY-WRIST-JOINT', 'WRIST JOINT', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-WRIST', 'BOTH WRIST', 22000.00
    UNION ALL SELECT 'XRAY-FOOT-APLAT', 'FOOT(AP/LAT)', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-FOOT-APLAT', 'BOTH FOOT(AP/LAT)', 22000.00
    UNION ALL SELECT 'XRAY-ELBOW-APLAT', 'ELBOW(AP/LAT)', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-ELBOW', 'BOTH ELBOW', 22000.00
    UNION ALL SELECT 'XRAY-ANKLE-APLAT', 'ANKLE (AP/LAT)', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-ANKLE', 'BOTH ANKLE', 22000.00
    UNION ALL SELECT 'XRAY-KNEE-JOINT-APLAT', 'KNEE JOINT AP/LAT', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-KNEES', 'BOTH KNEES', 22000.00
    UNION ALL SELECT 'XRAY-LEG-APLAT', 'LEG (AP/LAT)', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-LEG', 'BOTH LEG', 22000.00
    UNION ALL SELECT 'XRAY-FOREARM-APLAT', 'FOREARM (AP/LAT)', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-FOREARM', 'BOTH FOREARM', 22000.00
    UNION ALL SELECT 'XRAY-HUMERUS-APLAT', 'HUMERUS (AP/LAT)', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-HUMERUS', 'BOTH HUMERUS', 22000.00
    UNION ALL SELECT 'XRAY-THIGH-FEMUR-APLAT', 'THIGH (FEMUR) AP/LAT', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-THIGH', 'BOTH THIGH', 22000.00
    UNION ALL SELECT 'XRAY-LUMBAR-SAC-SPINE', 'LUMBAR SAC SPINE', 18000.00
    UNION ALL SELECT 'XRAY-CERVICAL-SPINE', 'CERVICAL SPINE', 18000.00
    UNION ALL SELECT 'XRAY-THORACIC-SPINE', 'THORACIC SPINE', 18000.00
    UNION ALL SELECT 'XRAY-PELVIC', 'PELVIC', 12000.00
    UNION ALL SELECT 'XRAY-HIP-JOINT', 'HIP JOINT', 12000.00
    UNION ALL SELECT 'XRAY-BOTH-HIP-JOINTS', 'BOTH HIP JOINTS', 22000.00
    UNION ALL SELECT 'XRAY-SHOULDER-CLAVICLE', 'SHOULDER JOINT / CLAVICLE', 12000.00
    UNION ALL SELECT 'XRAY-FINGER', 'FINGER', 12000.00
    UNION ALL SELECT 'XRAY-SKULL', 'SKULL', 18000.00
    UNION ALL SELECT 'XRAY-CHEST-AP-CXR', 'CHEST (AP) CXR', 12000.00
    UNION ALL SELECT 'XRAY-MANDIBLES', 'MANDIBLES', 12000.00
    UNION ALL SELECT 'XRAY-ABDOMEN', 'ABDOMEN', 18000.00
) seed
INNER JOIN departments d
    ON d.id = (
        SELECT d2.id
        FROM departments d2
        WHERE d2.department_name IN ('X-Ray', 'Radiology')
        ORDER BY CASE d2.department_name WHEN 'X-Ray' THEN 0 ELSE 1 END, d2.id
        LIMIT 1
    )
INNER JOIN users u
    ON u.id = (
        SELECT u2.id
        FROM users u2
        ORDER BY CASE WHEN u2.username = 'walter' THEN 0 ELSE 1 END, u2.id
        LIMIT 1
    )
WHERE NOT EXISTS (
    SELECT 1
    FROM billable_items existing
    WHERE existing.item_code = seed.item_code
);
